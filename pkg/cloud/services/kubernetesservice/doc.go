// Package kubernetesservice is CAPIBM's client for the IBM Cloud Kubernetes Service API (IKS and ROKS on VPC Gen2),
// used by the managed Kubernetes controllers.
//
// Why a package of its own, and not the SDK directly:
//
//   - The controllers speak CAPIBM domain types (types.go), never SDK models. The pinned
//     github.com/IBM-Cloud/container-services-go-sdk (commit 61af133) misses or mis-models a few operations; those are
//     implemented as compat functions on the SDK client's own BaseService, each with a COMPAT header naming the defect
//     and when to delete it. Replacing a compat function by a regenerated SDK method then changes no caller.
//   - Errors are reduced to one shape, APIError, built from go-sdk-core's DetailedResponse, and classified per
//     operation by Classify. errors.As on core.HTTPProblem does not work with this SDK generation, so callers must not
//     try it.
//   - Every request waits on one injected RequestLimiter inside the HTTP transport, below go-sdk-core and below the
//     compat paths, because IBM limits the API per source IP, whatever credentials a client uses.
//
// Conventions this package follows:
//
//   - Credentials and configuration are explicit arguments (ServiceOptions). Nothing here reads the environment, an
//     external credentials file or process-wide state, and the SDK's UsingExternalConfig constructor is never used.
//     The HTTP transport honours the standard proxy variables through net/http, like every other CAPIBM client; no IBM
//     credential or endpoint comes from the environment.
//   - SDK retries stay off. go-sdk-core would also retry POSTs (createCluster, createWorkerPool), which must never be
//     resent blindly; controller-runtime's requeue is the retry loop.
//   - No IBM free text is copied into a domain type that controllers store in status; IBM's descriptions reach
//     operators only through error messages and events.
//   - The interface is mocked with gomock (mock/kubernetesservice_generated.go, regenerated by make generate-go), and
//     this package's own tests run against httptest servers fed with the scrubbed live fixtures in testdata/.
package kubernetesservice
